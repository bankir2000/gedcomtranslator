// ===================== ВІДКРИТТЯ СТОРІНКИ: НОВА ВКЛАДКА АБО ЗАПАСНИЙ ПЕРЕХІД =====================
// У звичайному браузері window.open(url, '_blank') відкриває нову вкладку.
// Але в деяких обгортках (типово — Android WebView без явної підтримки
// кількох вікон, як-от у застосунках, що подають сторінку через локальний
// http://127.0.0.1:.../ сервер) виклик window.open МОВЧКИ повертає null і
// НІЧОГО не відбувається — без помилки в консолі, без попередження про
// блокування поп-апу. Єдиний надійний спосіб це виявити — перевірити
// результат window.open і, якщо це null/undefined, перейти на сторінку
// в тій самій вкладці замість того, щоб просто нічого не робити.

/**
 * @param {string} url - адреса сторінки, яку відкриваємо
 * @returns {boolean} true — відкрито в новій вкладці/вікні; false — перейшли в поточній
 */
export function openPageOrNavigate(url) {
  let win = null;
  try {
    win = window.open(url, '_blank');
  } catch {
    win = null;
  }
  if (!win) {
    window.location.href = url;
    return false;
  }
  return true;
}

/**
 * Закриває поточну вкладку/вікно (якщо це можливо — лише для вікон,
 * відкритих скриптом), а якщо ні — повертається на вказану сторінку
 * (типово index.html) у тій самій вкладці. Викликати саме так, а не просто
 * `window.close()`, бо в середовищах без підтримки кількох вікон ця сторінка
 * могла бути відкрита через запасний перехід (openPageOrNavigate) у тій самій
 * вкладці — і window.close() там нічого не зробить, залишивши користувача
 * на "мертвій" кнопці.
 * @param {string} fallbackUrl
 */
export function closeOrNavigateBack(fallbackUrl = 'index.html') {
  window.close();
  // Якщо виконання дійшло сюди — вікно НЕ закрилось (не було відкрите
  // скриптом). Невелика затримка на випадок, якщо close() усе ж таки
  // асинхронно спрацює в останній момент.
  setTimeout(() => { window.location.href = fallbackUrl; }, 50);
}
