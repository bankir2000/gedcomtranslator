// ===================== TRANSLITERATION (RU → UK) =====================
export const CHAR_MAP = {
  'а':'а','А':'А','б':'б','Б':'Б','в':'в','В':'В','г':'г','Г':'Г','д':'д','Д':'Д',
  'е':'е','Е':'Е','ё':'йо','Ё':'Йо','ж':'ж','Ж':'Ж','з':'з','З':'З','и':'и','И':'И',
  'й':'й','Й':'Й','к':'к','К':'К','л':'л','Л':'Л','м':'м','М':'М','н':'н','Н':'Н',
  'о':'о','О':'О','п':'п','П':'П','р':'р','Р':'Р','с':'с','С':'С','т':'т','Т':'Т',
  'у':'у','У':'У','ф':'ф','Ф':'Ф','х':'х','Х':'Х','ц':'ц','Ц':'Ц','ч':'ч','Ч':'Ч',
  'ш':'ш','Ш':'Ш','щ':'щ','Щ':'Щ','ъ':'','Ъ':'','ы':'и','Ы':'И','ь':'ь','Ь':'Ь',
  'э':'е','Э':'Е','ю':'ю','Ю':'Ю','я':'я','Я':'Я',
};

export function translitRuUk(s) {
  let r = '';
  for (const c of s) r += CHAR_MAP[c] ?? c;
  return r;
}

export function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
